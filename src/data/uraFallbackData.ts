import { UraTransactionRecord } from "../types";

export function formatContractDate(mmyy: string): string {
  if (!mmyy || mmyy.length !== 4) return mmyy || "Recent";
  const monthNum = parseInt(mmyy.substring(0, 2), 10);
  const yearShort = mmyy.substring(2, 4);
  const months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
  const monthName = months[monthNum - 1] || "Month";
  return `${monthName} 20${yearShort}`;
}

